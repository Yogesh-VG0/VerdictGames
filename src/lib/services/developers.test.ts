import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { afterEach, beforeAll, beforeEach, describe, expect, it, vi } from 'vitest';
import { GAME_CARD_COLUMNS_WITH_DESC } from '@/lib/db/columns';
import { mapGameRow } from '@/lib/db/mappers';
import type { GameRow } from '@/lib/supabase/types';
import { isPublicSafeGame } from '@/lib/utils/publicSafety';
import { slugify } from '@/lib/utils/slugify';

const require = createRequire(import.meta.url);
require('next/dist/server/node-environment');
const { workAsyncStorage } = require('next/dist/server/app-render/work-async-storage.external');
const [fixture] = JSON.parse(readFileSync(new URL('../../../scripts/fixtures/public-games.json', import.meta.url), 'utf8')) as GameRow[];
const entries = new Map<string, unknown>();
const incrementalCache = {
  generateSimpleCacheKey: async (key: string) => key,
  get: async (key: string) => entries.get(key) ?? null,
  set: async (key: string, value: unknown) => { entries.set(key, { value, isStale: false }); },
};

let loadDeveloperHub: typeof import('./developers').loadDeveloperHub;
let rows: GameRow[];
let requests: Array<{ kind: 'directory' | 'hub'; columns: string; after: string; limit: number; rowCount: number }>;

function game(id: number, developer: string, overrides: Partial<GameRow> = {}): GameRow {
  return {
    ...fixture,
    id: String(id).padStart(6, '0'),
    slug: `sample-game-${id}`,
    title: `Sample Game ${id}`,
    developer,
    release_date: '2023-01-01',
    verdict_summary: 'Stored summary that is regenerated by the public mapper.',
    critic_source_count: 4,
    created_at: '2024-01-02T00:00:00.000Z',
    updated_at: '2024-01-03T00:00:00.000Z',
    ...overrides,
  };
}

function project(row: GameRow, columns: string) {
  return Object.fromEntries(columns.split(',').map(selection => {
    const [alias, from = alias] = selection.split(':');
    return [alias, row[from as keyof GameRow]];
  }));
}

async function read(slug: string) {
  const store: { route: string; incrementalCache: typeof incrementalCache; pendingRevalidates?: Record<string, Promise<unknown>> } = {
    route: '/developers/[slug]', incrementalCache,
  };
  const result: Awaited<ReturnType<typeof loadDeveloperHub>> = await workAsyncStorage.run(store, () => loadDeveloperHub(slug));
  await Promise.all(Object.values(store.pendingRevalidates ?? {}));
  return result;
}

describe('developer catalogue projections and cache', () => {
  beforeAll(async () => { ({ loadDeveloperHub } = await import('./developers')); });
  beforeEach(() => {
    entries.clear();
    rows = [];
    requests = [];
    vi.stubEnv('NEXT_PUBLIC_SUPABASE_URL', 'http://127.0.0.1:1');
    vi.stubEnv('NEXT_PUBLIC_SUPABASE_ANON_KEY', 'isolated-developer-fixture');
    vi.stubGlobal('fetch', async (input: string | URL | Request) => {
      const url = new URL(typeof input === 'string' ? input : input instanceof URL ? input.href : input.url);
      if (url.origin !== 'http://127.0.0.1:1' || url.pathname !== '/rest/v1/games') {
        throw new Error('Unexpected network request in the developer fixture');
      }
      const columns = url.searchParams.get('select') ?? '';
      const limit = Number(url.searchParams.get('limit'));
      const directory = url.searchParams.get('order') === 'developer.asc';
      const field = directory ? 'developer' : 'id';
      const names = url.searchParams.get('developer')?.replace(/^in\.\(|\)$/g, '').split(',') ?? [];
      const cursor = url.searchParams.getAll(field).find(value => value.startsWith('gt.'));
      const after = cursor?.slice(3) ?? '';
      const selected = rows.filter(row => row[field] > after && (directory || names.includes(row.developer)))
        .sort((left, right) => left[field] < right[field] ? -1 : Number(left[field] > right[field]))
        .slice(0, limit);
      requests.push({ kind: directory ? 'directory' : 'hub', columns, after, limit, rowCount: selected.length });
      return Response.json(selected.map(row => project(row, columns)));
    });
  });
  afterEach(() => { vi.unstubAllGlobals(); vi.unstubAllEnvs(); });

  it('reuses one paged directory across concurrent cold hubs without losing aliases', async () => {
    rows = [
      ...Array.from({ length: 1002 }, (_, i) => game(i + 10, 'A Repeated Name')),
      game(1, 'North Studio'), game(2, 'North-Studio'), game(3, 'South Studio'),
    ];
    const [north, south] = await Promise.all([read('north-studio'), read('south-studio')]);
    expect(north?.name).toBe('North Studio');
    expect(north?.games.map(entry => entry.developer)).toEqual(['North Studio', 'North-Studio']);
    expect(south?.gameCount).toBe(1);
    expect(await read('north-studio')).toEqual(north);
    expect(await read('../invalid')).toBeNull();
    expect(requests.filter(request => request.kind === 'directory')).toEqual([
      { kind: 'directory', columns: 'd:developer', after: '', limit: 1000, rowCount: 1000 },
      { kind: 'directory', columns: 'd:developer', after: 'A Repeated Name', limit: 1000, rowCount: 3 },
    ]);
    expect(requests.filter(request => request.kind === 'hub')).toHaveLength(2);
  });

  it('preserves the previous public payload, complete count, average and tie ordering across large hub pages', async () => {
    rows = Array.from({ length: 1502 }, (_, i) => game(i + 1, i % 2 ? 'North-Studio' : 'North Studio', {
      release_date: i % 5 === 0 ? '2024-01-01' : '2023-01-01',
      verdict_score: 75 + (i % 10),
    }));
    rows[0] = { ...rows[0], cover_image: '' };
    rows[1] = { ...rows[1], description: 'This is a hentai clicker.' };
    rows[2] = { ...rows[2], release_date: '2099-01-01', release_status: 'announced' };
    const expected = rows.filter(row => slugify(row.developer) === 'north-studio')
      .map(row => project(row, GAME_CARD_COLUMNS_WITH_DESC) as GameRow)
      .filter(row => row.cover_image && isPublicSafeGame(row)).map(mapGameRow)
      .sort((left, right) => right.releaseDate.localeCompare(left.releaseDate));
    expect(expected).toHaveLength(1500);

    const hub = await read('north-studio');
    expect(hub).toEqual({
      name: 'North Studio', slug: 'north-studio', gameCount: expected.length,
      averageScore: Math.round(expected.reduce((sum, entry) => sum + entry.score, 0) / expected.length),
      games: expected,
    });
    const pages = requests.filter(request => request.kind === 'hub');
    expect(pages.map(({ after, rowCount }) => [after, rowCount])).toEqual([
      ['', 500], ['000500', 500], ['001000', 500], ['001500', 2],
    ]);
    const selected = pages[0].columns.split(',');
    const omitted = GAME_CARD_COLUMNS_WITH_DESC.split(',').filter(column => !selected.includes(column));
    expect(omitted).toEqual(['verdict_summary', 'critic_source_count', 'created_at', 'updated_at']);
    expect(selected).toContain('description');
  });

  it('returns no hub for deleted games or a developer with only hidden games', async () => {
    rows = [
      game(1, 'North Studio'),
      game(2, 'Retired Studio'),
      game(3, 'Hidden Studio', { title: 'Hentai Clicker' }),
    ];
    await read('north-studio');
    rows = rows.filter(row => row.developer !== 'Retired Studio');
    expect(await read('retired-studio')).toBeNull();
    expect(await read('hidden-studio')).toBeNull();
    expect(requests.filter(request => request.kind === 'directory')).toHaveLength(1);
  });
});
